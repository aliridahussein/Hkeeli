/**
 * Rebuild vendor/three/three-hkeeli.min.js — the one three.js file the
 * courtyard loads.
 *
 *   npm install --no-save three@0.187.0 esbuild@0.25.10   (in a scratch folder)
 *   node tools/build-three.mjs <that folder>
 *
 * It reads every `import { … } from '…/vendor/three/three-hkeeli.min.js'` in
 * js/courtyard/, writes vendor/three/entry.js exporting exactly those names,
 * and has esbuild tree-shake and minify three.js down to them. The site itself
 * has no build step; this runs only when the scene starts using a three.js
 * class it didn't use before (the browser will say "does not provide an
 * export named …").
 */

import { readFileSync, readdirSync, writeFileSync, copyFileSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const work = resolve(process.argv[2] || '.');
const ADDONS = {
  mergeGeometries: 'three/addons/utils/BufferGeometryUtils.js',
  RoundedBoxGeometry: 'three/addons/geometries/RoundedBoxGeometry.js'
};

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : path.endsWith('.js') ? [path] : [];
  });
}

const names = new Set();
for (const file of files(join(ROOT, 'js', 'courtyard'))) {
  const source = readFileSync(file, 'utf8');
  for (const match of source.matchAll(/import\s*\{([^}]+)\}\s*from\s*'[^']*vendor\/three\/three-hkeeli\.min\.js'/g)) {
    match[1].split(',').map((s) => s.trim().split(/\s+as\s+/)[0]).filter(Boolean).forEach((n) => names.add(n));
  }
}

const core = [...names].filter((n) => !ADDONS[n]).sort();
const addons = [...names].filter((n) => ADDONS[n]).sort();
const entry = [
  '/*',
  ' * Generated by tools/build-three.mjs — the three.js names js/courtyard/ uses.',
  ' * Edit the scene, not this file; then re-run the script.',
  ' */',
  `export {\n  ${core.join(',\n  ')}\n} from 'three';`,
  ...addons.map((n) => `export { ${n} } from '${ADDONS[n]}';`),
  ''
].join('\n');
writeFileSync(join(ROOT, 'vendor', 'three', 'entry.js'), entry);
writeFileSync(join(work, 'entry.js'), entry);

// esbuild's own launcher, run by this Node: no shell, on any platform.
const esbuild = join(work, 'node_modules', 'esbuild', 'bin', 'esbuild');
execFileSync(process.execPath, [esbuild, 'entry.js', '--bundle', '--minify', '--format=esm', '--target=es2020', '--legal-comments=eof', '--outfile=out/three-hkeeli.min.js'], { cwd: work, stdio: 'inherit' });
copyFileSync(join(work, 'out', 'three-hkeeli.min.js'), join(ROOT, 'vendor', 'three', 'three-hkeeli.min.js'));
copyFileSync(join(work, 'node_modules', 'three', 'LICENSE'), join(ROOT, 'vendor', 'three', 'LICENSE'));
console.log(`${names.size} names; wrote vendor/three/three-hkeeli.min.js`);
